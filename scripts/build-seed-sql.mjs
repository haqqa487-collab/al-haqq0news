// Generates migrations/0002_seed.sql from content/seed-articles.js and content/settings.js.
// Run with: npm run db:seed-sql
import fs from "node:fs";
import { seedArticles } from "../content/seed-articles.js";
import { defaultSettings } from "../content/settings.js";

const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const lines = ["-- Launch content. Generated by scripts/build-seed-sql.mjs; do not edit by hand.", "-- Runs once per database (as a migration), so later edits in the admin area are never overwritten."];

for (const a of seedArticles) {
  const v = [a.slug, a.title, a.dek, a.kicker || "", a.section, a.type, JSON.stringify(a.tags || []), a.author || "Abdi Fatah",
    a.body.trim(), JSON.stringify(a.ledger || []), JSON.stringify(a.sources || []), JSON.stringify(a.hero || {}),
    a.featured ? 1 : 0, a.editorsPick ? 1 : 0, a.status || "published", a.publishedAt, a.updatedAt || a.publishedAt,
    a.lastVerified || null, a.updateNote || ""];
  lines.push(`INSERT OR IGNORE INTO articles (slug,title,dek,kicker,section,type,tags,author,body,ledger,sources,hero,featured,editors_pick,status,published_at,updated_at,last_verified,update_note) VALUES (${v.map(q).join(",")});`);
}
for (const [k, v] of Object.entries(defaultSettings)) {
  lines.push(`INSERT OR IGNORE INTO settings (key,value) VALUES (${q(k)},${q(JSON.stringify(v))});`);
}
fs.writeFileSync(new URL("../migrations/0002_seed.sql", import.meta.url), lines.join("\n") + "\n");
console.log(`Wrote ${seedArticles.length} articles and ${Object.keys(defaultSettings).length} settings to migrations/0002_seed.sql`);
